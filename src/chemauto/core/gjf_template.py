from __future__ import annotations

import re
from pathlib import Path
from typing import Iterable

_RE_LINK1 = re.compile(r"^\s*--link1--\s*$", re.I | re.M)
_RE_CHARGE_MULT = re.compile(r"^\s*(-?\d+)\s+(\d+)\s*$")


def _normalise(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _split_nonempty_blocks(step_text: str) -> list[str]:
    return [b.strip("\n") for b in re.split(r"\n\s*\n", step_text.strip()) if b.strip()]


def apply_structure_to_template(
    template_text: str,
    coordinate_lines: Iterable[str],
    charge: int,
    multiplicity: int,
    output_stem: str,
    source_name: str = "",
) -> str:
    """Insert coordinates into the first Gaussian job of a template.

    The template route, title and tail sections are retained. The first
    molecule specification is replaced by ``charge multiplicity`` plus the
    supplied Cartesian coordinates. The first job's ``%chk`` is updated to
    match the output file stem; if absent, it is inserted before the route.
    Later Link1 jobs are preserved unchanged.
    """
    text = _normalise(template_text)
    parts = _RE_LINK1.split(text)
    first = parts[0]
    blocks = _split_nonempty_blocks(first)
    if not blocks:
        raise ValueError("The GJF template is empty.")

    control = blocks[0].splitlines()
    route_index = next((i for i, line in enumerate(control) if line.lstrip().startswith("#")), None)
    if route_index is None:
        raise ValueError("The template does not contain a Gaussian route section (#...).")

    chk_line = f"%chk={output_stem}.chk"
    chk_index = next((i for i, line in enumerate(control) if line.strip().lower().startswith("%chk=")), None)
    if chk_index is None:
        control.insert(route_index, chk_line)
    else:
        control[chk_index] = chk_line
    blocks[0] = "\n".join(control)

    if len(blocks) < 2:
        blocks.append(f"Generated by ChemAuto from {source_name}".strip())
    elif not blocks[1].strip():
        blocks[1] = f"Generated by ChemAuto from {source_name}".strip()

    coords = [line.rstrip() for line in coordinate_lines if line.strip()]
    molecule = f"{int(charge)} {int(multiplicity)}\n" + "\n".join(coords)

    mol_index = None
    for i in range(2, len(blocks)):
        first_line = blocks[i].splitlines()[0] if blocks[i].splitlines() else ""
        if _RE_CHARGE_MULT.match(first_line):
            mol_index = i
            break
    if mol_index is None:
        if len(blocks) >= 2:
            blocks.insert(2, molecule)
        else:
            blocks.append(molecule)
    else:
        blocks[mol_index] = molecule

    first_new = "\n\n".join(blocks).rstrip() + "\n"
    if len(parts) == 1:
        return first_new + "\n"
    tail = "\n--Link1--\n".join(p.strip("\n") for p in parts[1:])
    return first_new.rstrip() + "\n\n--Link1--\n" + tail.rstrip() + "\n"


def build_minimal_gjf(
    coordinate_lines: Iterable[str],
    charge: int,
    multiplicity: int,
    output_stem: str,
    source_name: str = "",
) -> str:
    coords = "\n".join(line.rstrip() for line in coordinate_lines if line.strip())
    return (
        f"%chk={output_stem}.chk\n"
        "#p sp\n\n"
        f"Generated by ChemAuto from {source_name}\n\n"
        f"{int(charge)} {int(multiplicity)}\n"
        f"{coords}\n\n"
    )


def build_gjf_from_template_path(
    template_path: str | Path | None,
    coordinate_lines: Iterable[str],
    charge: int,
    multiplicity: int,
    output_stem: str,
    source_name: str = "",
) -> tuple[str, bool]:
    """Return generated text and whether a user template was used."""
    if template_path:
        path = Path(template_path)
        if path.is_file():
            text = path.read_text(encoding="utf-8", errors="ignore")
            return (
                apply_structure_to_template(
                    text, coordinate_lines, charge, multiplicity, output_stem, source_name
                ),
                True,
            )
    return (
        build_minimal_gjf(coordinate_lines, charge, multiplicity, output_stem, source_name),
        False,
    )
