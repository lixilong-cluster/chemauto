#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Remote CHK -> FCHK profile management and launcher.

Only non-sensitive connection parameters are persisted. Passwords are never
written by ChemAuto; the bundled PowerShell/OpenSSH workflow prompts in its own
visible console when authentication is needed.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Dict, List, Optional

from chemauto.infra.paths import get_resource_path, get_user_data_dir

PROFILE_FILE = get_user_data_dir() / "remote_formchk_profiles.json"
RUNNER_DIR = get_user_data_dir() / "remote_formchk"


@dataclass
class RemoteFormchkProfile:
    name: str = "Default"
    remote_user: str = ""
    remote_host: str = ""
    remote_port: int = 22
    remote_workdir: str = "/home/user/fchk"
    remote_exec_node: str = ""
    remote_command: str = "/home/user/bin/c2f"
    clean_remote_files: bool = True
    overwrite_local_fchk: bool = False
    scp_force_legacy: bool = False
    ssh_exe: str = ""
    scp_exe: str = ""

    def validate(self) -> List[str]:
        missing: List[str] = []
        for attr, label in (
            ("name", "Profile name"),
            ("remote_user", "Remote user"),
            ("remote_host", "Remote host"),
            ("remote_workdir", "Remote workdir"),
            ("remote_exec_node", "Execution node"),
            ("remote_command", "Remote command"),
        ):
            if not str(getattr(self, attr, "")).strip():
                missing.append(label)
        try:
            port = int(self.remote_port)
            if not 1 <= port <= 65535:
                missing.append("Remote port")
        except Exception:
            missing.append("Remote port")
        return missing


def load_profiles() -> Dict[str, RemoteFormchkProfile]:
    if not PROFILE_FILE.exists():
        return {}
    try:
        raw = json.loads(PROFILE_FILE.read_text(encoding="utf-8"))
    except Exception:
        return {}
    out: Dict[str, RemoteFormchkProfile] = {}
    for item in raw.get("profiles", []):
        try:
            profile = RemoteFormchkProfile(**item)
            if profile.name:
                out[profile.name] = profile
        except Exception:
            continue
    return out


def save_profiles(profiles: Dict[str, RemoteFormchkProfile], active: str = "") -> None:
    PROFILE_FILE.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "active": active,
        "profiles": [asdict(p) for p in profiles.values()],
        "security_note": "Passwords and private-key passphrases are never stored by ChemAuto.",
    }
    PROFILE_FILE.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")


def get_active_profile_name() -> str:
    if not PROFILE_FILE.exists():
        return ""
    try:
        raw = json.loads(PROFILE_FILE.read_text(encoding="utf-8"))
        return str(raw.get("active", ""))
    except Exception:
        return ""


def _yn(value: bool) -> str:
    return "yes" if value else "no"


def prepare_runner(profile: RemoteFormchkProfile) -> Path:
    missing = profile.validate()
    if missing:
        raise ValueError("Missing/invalid settings: " + ", ".join(missing))
    RUNNER_DIR.mkdir(parents=True, exist_ok=True)
    bundled = get_resource_path("chk_remote_formchk_v7_direct_simple.ps1")
    if not bundled.exists():
        raise FileNotFoundError(f"Bundled PowerShell runner not found: {bundled}")
    script = RUNNER_DIR / bundled.name
    shutil.copy2(bundled, script)
    ini = RUNNER_DIR / "remote_formchk_config.ini"
    ini.write_text(
        "\n".join([
            "# Generated by ChemAuto. Contains no password.",
            f"REMOTE_USER={profile.remote_user}",
            f"REMOTE_HOST={profile.remote_host}",
            f"REMOTE_PORT={int(profile.remote_port)}",
            "",
            f"REMOTE_WORKDIR={profile.remote_workdir}",
            f"REMOTE_EXEC_NODE={profile.remote_exec_node}",
            f"REMOTE_COMMAND={profile.remote_command}",
            "",
            f"CLEAN_REMOTE_FILES={_yn(profile.clean_remote_files)}",
            f"OVERWRITE_LOCAL_FCHK={_yn(profile.overwrite_local_fchk)}",
            f"SCP_FORCE_LEGACY={_yn(profile.scp_force_legacy)}",
            "",
            f"SSH_EXE={profile.ssh_exe}",
            f"SCP_EXE={profile.scp_exe}",
            "",
        ]),
        encoding="utf-8",
    )
    return script


def launch_remote_conversion(chk_path: str | Path, profile: RemoteFormchkProfile) -> subprocess.Popen:
    chk = Path(chk_path).resolve()
    if not chk.exists() or chk.suffix.casefold() != ".chk":
        raise ValueError(f"Not a valid CHK file: {chk}")
    script = prepare_runner(profile)
    powershell = shutil.which("powershell.exe") or shutil.which("powershell")
    if not powershell:
        raise FileNotFoundError("PowerShell was not found on this computer.")
    args = [
        powershell,
        "-NoProfile",
        "-ExecutionPolicy", "Bypass",
        "-File", str(script),
        str(chk),
    ]
    flags = getattr(subprocess, "CREATE_NEW_CONSOLE", 0)
    return subprocess.Popen(args, creationflags=flags)
